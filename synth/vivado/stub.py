#!/usr/bin/env python3
"""Emit a black-box stub for a SystemVerilog module: its header (parameters and ports) verbatim, no body, with
the Vivado (* black_box *) attribute. Used by run.sh -b to synthesise a block with chosen children left out, so
the utilisation report (and the synthesis time) is about the block itself.
Usage: stub.py [--null] rtl/foo.sv > foo_bb.sv   (one module per file; the header ends at the first ');';
--null drives the outputs low instead of declaring a black box)"""
import re
import sys

srcfile = [a for a in sys.argv[1:] if not a.startswith("--")][0]
src = open(srcfile).read()
src = re.sub(r"//[^\n]*", "", src)        # drop line comments: a ';' inside one ended the header early (sr_top, 2026-10-13)
m = re.search(r"^\s*module\s+\w+.*?\)\s*;", src, re.S | re.M)
if not m:
    sys.exit(f"{srcfile}: no module header found")
header = m.group(0)
if "--null" in sys.argv:
    # synthesizable stand-in: the header, every output driven to zero (for implementation trials, where a
    # black box is not allowed)
    outs = re.findall(r"^\s*output\s+(?:logic|wire|reg)?\s*(?:\[[^\]]+\]\s*)*(\w+)", header, re.M)
    print(f"// null stub of {srcfile} (generated by synth/vivado/stub.py --null): outputs tied low")
    print(header)
    for o in outs:
        print(f"    assign {o} = '0;")
    print("endmodule")
else:
    print(f"// black-box stub of {srcfile} (generated by synth/vivado/stub.py)")
    print("(* black_box *)")
    print(header)
    print("endmodule")
