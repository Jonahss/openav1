#!/usr/bin/env python3
"""rtl/mc_tables_pkg.sv from tb/av1_tables.py: the Subpel_Filters coefficients (6 filters x 16 phases x 8 taps, signed
9 bits) as a flat constant, read by mc_filt. Regenerate with: python3 tools/gen_mc_tables.py"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "tb"))
import av1_tables as T  # noqa: E402

F = T.Subpel_Filters
lines = ["// Generated by tools/gen_mc_tables.py from tb/av1_tables.py (spec Subpel_Filters). Do not edit.",
         "package mc_tables_pkg;",
         "    // subpel_tap(f, p, t): Subpel_Filters[f][p][t], signed 9 bits (-24 .. 128); entry (f * 16 + p) * 8 + t",
         "    localparam int SUBPEL_N = 6 * 16 * 8;",
         "    localparam logic signed [8:0] SUBPEL_TAPS [0:SUBPEL_N-1] = '{"]
vals = []
for f in range(6):
    for p in range(16):
        for t in range(8):
            v = F[f][p][t]
            vals.append(f"9'sd{v}" if v >= 0 else f"-9'sd{-v}")
for i in range(0, len(vals), 16):
    lines.append("        " + ", ".join(vals[i:i + 16]) + ("," if i + 16 < len(vals) else ""))
lines += ["    };",
          "    function automatic logic signed [8:0] subpel_tap(input logic [2:0] f, input logic [3:0] p, input logic [2:0] t);",
          "        return SUBPEL_TAPS[{f, p, t}];",
          "    endfunction",
          "endpackage"]
Path(__file__).resolve().parent.parent.joinpath("rtl", "mc_tables_pkg.sv").write_text("\n".join(lines) + "\n")
print("rtl/mc_tables_pkg.sv:", len(vals), "taps")
