#!/usr/bin/env python3
"""Plan a model-free Argon batch: every intra-only stream of a set (tools/argon_index.py census), grouped by the
frame-buffer size the RTL must be built with (FBX/FBY = log2 of the upscaled width / height, at least 10 x 9),
skipping streams above --max-pixels. Writes <out>/<class>.txt lists and <out>/run.sh, which makes the dav1d
reference pictures (no film grain: the Argon md5_no_film_grain semantics) and runs tb/runner.py dec_top per class,
up to --jobs classes at once (each in its own build dir, largest classes first) with --threads Verilator threads each.
Usage: tools/argon_batch.py <argon-set-dir> <out-dir> [--max-pixels N] [--skip file-with-stems] [--jobs J] [--threads T]
"""
import csv
import io
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
set_dir, out = Path(args[0]), Path(args[1])
max_px = int(sys.argv[sys.argv.index("--max-pixels") + 1]) if "--max-pixels" in sys.argv else 4_500_000
jobs = int(sys.argv[sys.argv.index("--jobs") + 1]) if "--jobs" in sys.argv else 0          # 0: one job per class
threads = int(sys.argv[sys.argv.index("--threads") + 1]) if "--threads" in sys.argv else 0   # 0: cores / jobs
skip = set()
if "--skip" in sys.argv:
    skip = set(Path(sys.argv[sys.argv.index("--skip") + 1]).read_text().split())
idx = subprocess.run([sys.executable, str(ROOT / "tools" / "argon_index.py"), str(set_dir)], capture_output=True, text=True, check=True).stdout
rows = list(csv.DictReader(io.StringIO(idx)))
classes = {}
pixels = {}
skipped = []
for r in rows:
    if r["intra_only_stream"] != "1":
        continue
    stem = Path(r["path"]).stem
    if stem in skip:
        continue
    w, h = int(r["max_w"]), int(r["max_h"])
    if w * h > max_px:
        skipped.append((stem, w, h))
        continue
    fbx = max(10, (w + 8 - 1).bit_length())      # +8: reconstruction overhang past the last 4x4 column
    fby = max(9, (h + 8 - 1).bit_length())
    classes.setdefault((fbx, fby), []).append(str(Path(r["path"]).resolve()))   # absolute: the simulation runs in its build dir
    pixels[(fbx, fby)] = pixels.get((fbx, fby), 0) + w * h
out.mkdir(parents=True, exist_ok=True)
jobs = jobs or len(classes)
threads = threads or max(1, (os.cpu_count() or 1) // jobs)
lines = ["#!/usr/bin/env bash", "# generated by tools/argon_batch.py", "cd \"$(dirname \"$0\")/../..\" && source env.sh", "mkdir -p refout"]
lines.append("for f in $(cat " + " ".join(str(out / f"fb{x}x{y}.txt") for (x, y) in sorted(classes)) + "); do")
lines.append("  s=$(basename $f .obu); [ -f refout/$s.yuv ] || prefix-trace/bin/dav1d -q -i $f -o refout/$s.yuv --muxer yuv --threads 1 --filmgrain 0; done")
lines.append(f"echo \"ARGON_START $(date -Is) @ $(git rev-parse --short HEAD) host=$(hostname) jobs={jobs} SIM_THREADS={threads}\" >> {out}/summary.txt")
lines.append("run_class() {  # $1 = fbXxY $2 = FBX $3 = FBY; own build dir (tb/runner.py keys it on FBX/FBY)")
lines.append(f"  SIM_FAST=1 SIM_THREADS={threads} FBX=$2 FBY=$3 TS_NOMODEL=1 TS_IVF=$(paste -sd, {out}/$1.txt) python tb/runner.py dec_top > {out}/$1.out 2>&1")
lines.append(f"  echo \"$1: $(grep -c 'identical to dav1d' {out}/$1.out) identical frames; $(grep -o 'AssertionError: [0-9]* / [0-9]* streams failed' {out}/$1.out | tail -1)\" >> {out}/summary.txt")
lines.append("}")
for (x, y), paths in sorted(classes.items(), key=lambda kv: (-pixels[kv[0]], kv[0])):   # most pixels first: the long poles start early
    name = f"fb{x}x{y}"
    (out / f"{name}.txt").write_text("\n".join(paths) + "\n")
    lines.append(f"while [ $(jobs -r | wc -l) -ge {jobs} ]; do wait -n; done; run_class {name} {x} {y} &")
lines.append("wait")
lines.append(f"echo BATCH_DONE $(date -Is) >> {out}/summary.txt")
(out / "run.sh").write_text("\n".join(lines) + "\n")
os.chmod(out / "run.sh", 0o755)
for (x, y), paths in sorted(classes.items()):
    print(f"fb{x}x{y}: {len(paths)} streams")
print(f"skipped (> {max_px} px): {skipped}")
print(f"wrote {out}/run.sh")
