#!/usr/bin/env python3
"""Plan a model-free Argon batch: every intra-only stream of a set (tools/argon_index.py census), grouped by the
frame-buffer size the RTL must be built with (FBX/FBY = log2 of the upscaled width / height, at least 10 x 9),
skipping streams above --max-pixels. Writes <out>/<class>.txt lists and <out>/run.sh, which makes the dav1d
reference pictures (no film grain: the Argon md5_no_film_grain semantics), builds dec_top once per class, then runs
one job per stream (sharing the class build, each in its own run dir), up to --jobs at once, biggest streams
first, with --threads Verilator threads each. Per-stream logs in <out>/<class>/<stem>.out, one summary line per class.
Usage: tools/argon_batch.py <argon-set-dir> <out-dir> [--max-pixels N] [--skip file-with-stems] [--jobs J] [--threads T] [--limit N]
"""
import csv
import io
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
set_dir, out = Path(args[0]), Path(args[1])
max_px = int(sys.argv[sys.argv.index("--max-pixels") + 1]) if "--max-pixels" in sys.argv else 4_500_000
jobs = int(sys.argv[sys.argv.index("--jobs") + 1]) if "--jobs" in sys.argv else 0          # 0: cores / 4
threads = int(sys.argv[sys.argv.index("--threads") + 1]) if "--threads" in sys.argv else 0   # 0: cores / jobs
limit = int(sys.argv[sys.argv.index("--limit") + 1]) if "--limit" in sys.argv else 0         # smoke tests: first N streams
skip = set()
if "--skip" in sys.argv:
    skip = set(Path(sys.argv[sys.argv.index("--skip") + 1]).read_text().split())
idx = subprocess.run([sys.executable, str(ROOT / "tools" / "argon_index.py"), str(set_dir)], capture_output=True, text=True, check=True).stdout
rows = list(csv.DictReader(io.StringIO(idx)))
classes = {}
streams = []
skipped = []
for r in rows:
    if r["intra_only_stream"] != "1":
        continue
    stem = Path(r["path"]).stem
    if stem in skip:
        continue
    w, h = int(r["max_w"]), int(r["max_h"])
    if w * h > max_px:
        skipped.append((stem, w, h))
        continue
    fbx = max(10, (w + 8 - 1).bit_length())      # +8: reconstruction overhang past the last 4x4 column
    fby = max(9, (h + 8 - 1).bit_length())
    path = str(Path(r["path"]).resolve())                                        # absolute: the simulation runs in its run dir
    if limit and len(streams) >= limit:
        continue
    classes.setdefault((fbx, fby), []).append(path)
    streams.append((w * h * int(r["n_frames"]), fbx, fby, path))                  # work estimate for the job order
out.mkdir(parents=True, exist_ok=True)
jobs = jobs or max(1, (os.cpu_count() or 1) // 4)
threads = threads or max(1, (os.cpu_count() or 1) // jobs)
lines = ["#!/usr/bin/env bash", "# generated by tools/argon_batch.py", "cd \"$(dirname \"$0\")/../..\" && source env.sh", "mkdir -p refout"]
lines.append("for f in $(cat " + " ".join(str(out / f"fb{x}x{y}.txt") for (x, y) in sorted(classes)) + "); do")
lines.append("  s=$(basename $f .obu); [ -f refout/$s.yuv ] || prefix-trace/bin/dav1d -q -i $f -o refout/$s.yuv --muxer yuv --threads 1 --filmgrain 0; done")
lines.append(f"echo \"ARGON_START $(date -Is) @ $(git rev-parse --short HEAD) host=$(hostname) jobs={jobs} SIM_THREADS={threads} streams={len(streams)}\" >> {out}/summary.txt")
# 1. one Verilator build per class (build/dec_top_fb<X>x<Y>), in parallel
lines.append("build_class() { SIM_FAST=1 SIM_THREADS=" + str(threads) + " FBX=$1 FBY=$2 TS_BUILD_ONLY=1 python tb/runner.py dec_top > " + str(out) + "/build-fb$1x$2.out 2>&1 || echo \"BUILD FAILED fb$1x$2\" >> " + str(out) + "/summary.txt; }")
for (x, y), paths in sorted(classes.items()):
    (out / f"fb{x}x{y}.txt").write_text("\n".join(paths) + "\n")
    (out / f"fb{x}x{y}").mkdir(exist_ok=True)
    lines.append(f"while [ $(jobs -r | wc -l) -ge {jobs} ]; do wait -n; done; build_class {x} {y} &")
lines.append("wait")
# 2. one job per stream, biggest first, sharing the class build; its own run dir two levels down (relative paths)
lines.append("run_stream() {  # $1 = fbXxY $2 = FBX $3 = FBY $4 = stream; run dir build/run-$1-<stem>")
lines.append("  local s=$(basename $4 .obu)")
lines.append(f"  SIM_FAST=1 SIM_THREADS={threads} FBX=$2 FBY=$3 TS_NOMODEL=1 TS_IVF=$4 TS_TEST_DIR=build/run-$1-$s python tb/runner.py dec_top > {out}/$1/$s.out 2>&1")
lines.append("}")
for _, x, y, path in sorted(streams, key=lambda t: -t[0]):
    lines.append(f"while [ $(jobs -r | wc -l) -ge {jobs} ]; do wait -n; done; run_stream fb{x}x{y} {x} {y} {path} &")
lines.append("wait")
# 3. one summary line per class
for (x, y) in sorted(classes):
    name = f"fb{x}x{y}"
    n = len(classes[(x, y)])
    lines.append(f"echo \"{name}: $(cat {out}/{name}/*.out | grep -c 'identical to dav1d') identical frames; $(( {n} - $(grep -l 'PASS=1' {out}/{name}/*.out | wc -l) )) of {n} streams failed\" >> {out}/summary.txt")
lines.append(f"echo BATCH_DONE $(date -Is) >> {out}/summary.txt")
(out / "run.sh").write_text("\n".join(lines) + "\n")
os.chmod(out / "run.sh", 0o755)
for (x, y), paths in sorted(classes.items()):
    print(f"fb{x}x{y}: {len(paths)} streams")
print(f"skipped (> {max_px} px): {skipped}")
print(f"wrote {out}/run.sh")
