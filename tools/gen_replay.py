#!/usr/bin/env python3
"""Generate a gate-level replay testbench for a block from its port list.

  tools/gen_replay.py rtl/<block>.sv [--clk clk] [--param NAME=VAL ...] [--gate VALID:sig,sig,...] > tb/gate/replay_<block>.sv

The testbench drives per-cycle input vectors (tools/vcd2vec.py, inputs in port order, clk excluded) and compares every
output each cycle; outputs listed after --gate are compared only when the named output is 1 in the recorded vector
(for registers that are don't-care while idle). Prints the vcd2vec --in/--out lists to stderr. Parameters are taken
from their defaults unless overridden; widths may use simple expressions of them."""
import re, sys, argparse

ap = argparse.ArgumentParser()
ap.add_argument('src'); ap.add_argument('--clk', default='clk'); ap.add_argument('--param', action='append', default=[])
ap.add_argument('--gate', default='')
a = ap.parse_args()
def strip(s): return re.sub(r'//[^\n]*', '', s)
text = strip(open(a.src).read())
m = re.search(r'\bmodule\s+(\w+)\s*(?:import\s+[^;]+;\s*)*(#\s*\((.*?)\))?\s*\((.*?)\);', text, re.S)
if not m: sys.exit('module header not found')
name, plist, ports = m.group(1), m.group(3) or '', m.group(4)
params = {}
for pm in re.finditer(r'parameter\s+(?:\w+\s+)?(\w+)\s*=\s*([^,\n]+)', strip(plist)):
    params[pm.group(1)] = pm.group(2).strip()
import glob, os
# localparams of the module body and of every package next to it (widths often use them)
for src in [a.src] + glob.glob(os.path.join(os.path.dirname(a.src), '*pkg*.sv')):
    for lm in re.finditer(r'localparam\s+(?:\w+\s+)?(?:\[[^\]]*\]\s*)?(\w+)\s*=\s*([^,;\n]+)', strip(open(src).read())):
        params.setdefault(lm.group(1), lm.group(2).strip())
for p in a.param:
    k, v = p.split('='); params[k] = v
def ev(expr):
    e = expr
    for _ in range(5):
        for k, v in params.items(): e = re.sub(r'\b%s\b' % k, '(%s)' % v, e)
    e = e.replace('$clog2', 'clog2')
    return int(eval(e, {'clog2': lambda x: (int(x) - 1).bit_length()}))
# packed struct / enum typedefs from the block and its packages, for struct-typed ports
alltext = '\n'.join(strip(open(f).read()) for f in [a.src] + glob.glob(os.path.join(os.path.dirname(a.src), '*pkg*.sv')))
typedefs = {}
for tm in re.finditer(r'typedef\s+struct\s+packed\s*\{(.*?)\}\s*(\w+)\s*;', alltext, re.S):
    typedefs[tm.group(2)] = ('struct', tm.group(1))
for tm in re.finditer(r'typedef\s+enum\s+(?:logic|bit)\s*(\[([^\]]+)\])?\s*\{[^}]*\}\s*(\w+)\s*;', alltext, re.S):
    typedefs[tm.group(3)] = ('enum', tm.group(2) or '0:0')
def rng_width(rng):
    hi, lo = rng.split(':'); return ev(hi) - ev(lo) + 1
def type_width(t):
    kind, body = typedefs[t]
    if kind == 'enum': return rng_width(body)
    total = 0
    for mem in body.split(';'):
        mem = mem.strip()
        if not mem: continue
        mm = re.match(r'(\w+)\s*(signed\s+)?(\[([^\]]+)\])?\s*([\w\s,]+)$', mem)
        if not mm: sys.exit(f'cannot parse struct member: {mem}')
        base, _, _, rng, names = mm.groups()
        n = len([x for x in names.split(',') if x.strip()])
        if base in typedefs: w = type_width(base)
        elif rng: w = rng_width(rng)
        else: w = 1
        total += w * n
    return total
ins, outs = [], []
kind = width = None; signed = False
for decl in strip(ports).split(','):
    d = decl.strip()
    if not d: continue
    dm = re.match(r'(input|output)\s+(?:(logic|wire|reg)\s+)?(signed\s+)?(?:(\w+_t)\s+)?(\[([^\]]+)\])?\s*(\w+)\s*$', d)
    if dm:
        kind, _, sg, tname, _, rng, pname = dm.groups()
        signed = bool(sg)
        width = type_width(tname) if tname else (rng_width(rng) if rng else 1)
    else:
        bm = re.match(r'(\w+)\s*$', d)
        if not bm or kind is None: sys.exit(f'cannot parse port: {d}')
        pname = bm.group(1)
    (ins if kind == 'input' else outs).append((pname, width, signed))
ins_v = [p for p in ins if p[0] != a.clk]
gate_sig, gated = (a.gate.split(':')[0], a.gate.split(':')[1].split(',')) if a.gate else (None, [])
NI = sum(w for _, w, _ in ins_v); NO = sum(w for _, w, _ in outs)
print(f"--in {','.join(p for p, _, _ in ins_v)} --out {','.join(p for p, _, _ in outs)}   # NI={NI} NO={NO}", file=sys.stderr)
def decl(p, w, s): return f"logic {'signed ' if s else ''}{f'[{w-1}:0] ' if w > 1 else ''}{p};"
# bit positions of outputs within the packed vector (MSB first)
pos = {}; off = NO
for p, w, _ in outs: off -= w; pos[p] = (off + w - 1, off)
always = [p for p, _, _ in outs if p not in gated]
cmp_always = ' || '.join(f"{p} !== vout[n][{pos[p][0]}:{pos[p][1]}]" for p in always) or '1\'b0'
cmp_gated = ' || '.join(f"{p} !== vout[n][{pos[p][0]}:{pos[p][1]}]" for p in gated)
gate_expr = f" || (vout[n][{pos[gate_sig][0]}] && ({cmp_gated}))" if gate_sig else ''
print(f'''// Generated by tools/gen_replay.py from {a.src}: gate-level replay of recorded per-cycle vectors.
//   inputs  (MSB first): {' '.join(f"{p}[{w}]" for p, w, _ in ins_v)}
//   outputs (MSB first): {' '.join(f"{p}[{w}]" for p, w, _ in outs)}
`timescale 1ns/1ps
module replay_{name};
    localparam int NI = {NI};
    localparam int NO = {NO};
    localparam int MAXV = 400000;
    logic [NI-1:0] vin [0:MAXV-1];
    logic [NO-1:0] vout [0:MAXV-1];
    logic {a.clk} = 0;
''' + '\n'.join('    ' + decl(p, w, s) for p, w, s in ins_v + outs) + f'''
    {name} dut (.*);
    int n, errs, cmp;
    string vecfile;
    initial begin
        if (!$value$plusargs("vec=%s", vecfile)) vecfile = "vectors.hex";
        for (int i = 0; i < MAXV; i++) vin[i] = 'x;
        $readmemh(vecfile, vin, 0, MAXV-1);
        $readmemh({{vecfile, ".out"}}, vout, 0, MAXV-1);
    end
    initial begin
        errs = 0; cmp = 0; n = 0;
        while (n < MAXV && vin[n] !== 'x) begin
            {{{', '.join(p for p, _, _ in ins_v)}}} = vin[n];
            #4;
            if (n > 2) begin
                cmp++;
                if ({cmp_always}{gate_expr}) begin
                    errs++;
                    if (errs <= 100000) $display("MISMATCH cycle %0d: got %h exp %h", n, {{{', '.join(p for p, _, _ in outs)}}}, vout[n]);
                end
            end
            #1 {a.clk} = 1; #5 {a.clk} = 0;
            n++;
        end
        $display("REPLAY %s: %0d cycles, %0d compared, %0d mismatches -> %s", vecfile, n, cmp, errs, errs == 0 ? "PASS" : "FAIL");
        $finish;
    end
endmodule
''')
