#!/usr/bin/env python3
"""Generate a gate-level replay testbench for a block from its port list.

  tools/gen_replay.py rtl/<block>.sv [--clk clk] [--param NAME=VAL ...] [--gate VALID:sig,sig,...] > tb/gate/replay_<block>.sv

The testbench drives per-cycle input vectors (tools/vcd2vec.py, inputs in port order, clk excluded) and compares every
output each cycle; outputs listed after --gate are compared only when the named output is 1 in the recorded vector
(for registers that are don't-care while idle). Prints the vcd2vec --in/--out lists to stderr. Parameters are taken
from their defaults unless overridden; widths may use simple expressions of them."""
import re, sys, argparse

ap = argparse.ArgumentParser()
ap.add_argument('src'); ap.add_argument('--clk', default='clk'); ap.add_argument('--param', action='append', default=[])
ap.add_argument('--maxv', type=int, default=800000, help='vector capacity (a whole-decoder multi-frame recording is ~700k cycles)')
ap.add_argument('--gen2x', default=None, help='a 2x clock port generated by the harness (two rising edges per clk cycle, one aligned with clk\'s), not recorded')
ap.add_argument('--genphase', default=None, help='the phase port that goes with --gen2x: 1 at the mid-cycle 2x edge, 0 at the aligned one')
ap.add_argument('--gate', action='append', default=[], help='VALID:sig,sig — compare those outputs only when VALID is 1 in the recorded vector (repeatable; an output under several gates is compared when any is 1)')
a = ap.parse_args()
def strip(s): return re.sub(r'//[^\n]*', '', s)
text = strip(open(a.src).read())
m = re.search(r'\bmodule\s+(\w+)\s*(?:import\s+[^;]+;\s*)*(#\s*\((.*?)\))?\s*\((.*?)\);', text, re.S)
if not m: sys.exit('module header not found')
name, plist, ports = m.group(1), m.group(3) or '', m.group(4)
params = {}
for pm in re.finditer(r'parameter\s+(?:\w+\s+)?(\w+)\s*=\s*([^,\n]+)', strip(plist)):
    params[pm.group(1)] = pm.group(2).strip()
import glob, os
# localparams of the module body and of every package next to it (widths often use them)
for src in [a.src] + glob.glob(os.path.join(os.path.dirname(a.src), '*pkg*.sv')):
    for lm in re.finditer(r'localparam\s+(?:\w+\s+)?(?:\[[^\]]*\]\s*)?(\w+)\s*=\s*([^,;\n]+)', strip(open(src).read())):
        params.setdefault(lm.group(1), lm.group(2).strip())
for p in a.param:
    k, v = p.split('='); params[k] = v
def ev(expr):
    e = expr
    for _ in range(5):
        for k, v in params.items(): e = re.sub(r'\b%s\b' % k, '(%s)' % v, e)
    e = e.replace('$clog2', 'clog2')
    return int(eval(e, {'clog2': lambda x: (int(x) - 1).bit_length()}))
# packed struct / enum typedefs from the block and its packages, for struct-typed ports
alltext = '\n'.join(strip(open(f).read()) for f in [a.src] + glob.glob(os.path.join(os.path.dirname(a.src), '*pkg*.sv')))
typedefs = {}
for tm in re.finditer(r'typedef\s+struct\s+packed\s*\{(.*?)\}\s*(\w+)\s*;', alltext, re.S):
    typedefs[tm.group(2)] = ('struct', tm.group(1))
for tm in re.finditer(r'typedef\s+enum\s+(?:logic|bit)\s*(\[([^\]]+)\])?\s*\{[^}]*\}\s*(\w+)\s*;', alltext, re.S):
    typedefs[tm.group(3)] = ('enum', tm.group(2) or '0:0')
def rng_width(rng):
    hi, lo = rng.split(':'); return ev(hi) - ev(lo) + 1
def members(t):
    """[(name, width, base_type_or_None)] of a packed struct, in declaration order (first = MSB)."""
    kind, body = typedefs[t]
    out = []
    for mem in body.split(';'):
        mem = mem.strip()
        if not mem: continue
        mm = re.match(r'(\w+)\s*(signed\s+)?(\[([^\]]+)\])?\s*([\w\s,]+)$', mem)
        if not mm: sys.exit(f'cannot parse struct member: {mem}')
        base, _, _, rng, names = mm.groups()
        for nm in [x.strip() for x in names.split(',') if x.strip()]:
            if base in typedefs: out.append((nm, type_width(base), base))
            elif rng: out.append((nm, rng_width(rng), None))
            else: out.append((nm, 1, None))
    return out
def type_width(t):
    kind, body = typedefs[t]
    if kind == 'enum': return rng_width(body)
    return sum(w for _, w, _ in members(t))
def leaf_fields(t, prefix, hi):
    """Vivado flattens a struct port into one port per leaf field named \\port[f] (nested: \\port[f][g]):
    [(escaped_name, hi, lo)] with bit positions in the packed vector."""
    out = []
    for nm, w, base in members(t):
        if base is not None and typedefs[base][0] == 'struct':
            out += leaf_fields(base, f'{prefix}[{nm}]', hi)
        else:
            out.append((f'{prefix}[{nm}]', hi, hi - w + 1))
        hi -= w
    return out
ins, outs = [], []
port_struct = {}
kind = width = None; signed = False
stype = None
for decl in strip(ports).split(','):
    d = decl.strip()
    if not d: continue
    dm = re.match(r'(input|output)\s+(?:(logic|wire|reg)\s+)?(signed\s+)?(?:(\w+_t)\s+)?(\[([^\]]+)\])?\s*(\w+)\s*$', d)
    if dm:
        kind, _, sg, tname, _, rng, pname = dm.groups()
        signed = bool(sg)
        width = type_width(tname) if tname else (rng_width(rng) if rng else 1)
        stype = tname if tname and typedefs[tname][0] == 'struct' else None
    else:
        bm = re.match(r'(\w+)\s*$', d)
        if not bm or kind is None: sys.exit(f'cannot parse port: {d}')
        pname = bm.group(1)
    (ins if kind == 'input' else outs).append((pname, width, signed))
    port_struct[pname] = stype
gen_ports = [x for x in (a.gen2x, a.genphase) if x]
ins_v = [p for p in ins if p[0] != a.clk and p[0] not in gen_ports]
gates = {}      # output -> [valid signals]
for g in a.gate:
    v, outs_g = g.split(':')
    for o in outs_g.split(','): gates.setdefault(o, []).append(v)
gated = list(gates)
NI = sum(w for _, w, _ in ins_v); NO = sum(w for _, w, _ in outs)
print(f"--in {','.join(p for p, _, _ in ins_v)} --out {','.join(p for p, _, _ in outs)}   # NI={NI} NO={NO}", file=sys.stderr)
def decl(p, w, s): return f"logic {'signed ' if s else ''}{f'[{w-1}:0] ' if w > 1 else ''}{p};"
# bit positions of outputs within the packed vector (MSB first)
pos = {}; off = NO
for p, w, _ in outs: off -= w; pos[p] = (off + w - 1, off)
always = [p for p, _, _ in outs if p not in gated]
cmp_always = ' || '.join(f"{p} !== vout[n][{pos[p][0]}:{pos[p][1]}]" for p in always) or '1\'b0'
def gate_term(p):
    v = ' || '.join(f"vout[n][{pos[g][0]}]" for g in gates[p])
    return f"(({v}) && {p} !== vout[n][{pos[p][0]}:{pos[p][1]}])"
gate_expr = ''.join(f" || {gate_term(p)}" for p in gated)
# the same gates for the X-masked compare: a mask that is 0 over a gated output while its strobes are low
gmask_body = ''.join("        gmask[%d:%d] = {%d{(%s)}};\n" % (pos[p][0], pos[p][1], pos[p][0] - pos[p][1] + 1,
                     ' || '.join("e[%d]" % pos[g][0] for g in gates[p])) for p in gated)
gmask_fn = ("    function automatic logic [NO-1:0] gmask(input logic [NO-1:0] e);   // 0 over outputs that are don't-care this cycle\n"
            "        gmask = '1;\n" + gmask_body + "    endfunction\n")
def conn(p, w, stype):
    if stype is None: return f'.{p}({p})'
    return ', '.join(f'.\\{nm} ({p}[{hi}:{lo}])' if hi != lo else f'.\\{nm} ({p}[{hi}])' for nm, hi, lo in leaf_fields(stype, p, w - 1))
netlist_ports = ', '.join([f'.{a.clk}({a.clk})'] + [f'.{g}({g})' for g in gen_ports] + [conn(p, w, port_struct[p]) for p, w, _ in ins_v + outs])
if a.gen2x:
    ph = a.genphase
    # clk rises with a 2x edge (phase 0), the 2x clock rises again mid-cycle (phase 1); phase set on the 2x falling edges
    edge_seq_main = f"{a.clk} = 1; {a.gen2x} = 1; #2.5 {a.gen2x} = 0; " + (f"{ph} = 1; " if ph else "") + f"#2.5 {a.gen2x} = 1; {a.clk} = 0; #2.5 {a.gen2x} = 0; " + (f"{ph} = 0; " if ph else "") + "#2.5;"
    edge_seq = "#5 " + edge_seq_main
else:
    edge_seq_main = f"{a.clk} = 1; #5 {a.clk} = 0;"
    edge_seq = f"#5 {a.clk} = 1; #5 {a.clk} = 0;"
print(f'''// Generated by tools/gen_replay.py from {a.src}: gate-level replay of recorded per-cycle vectors.
//   inputs  (MSB first): {' '.join(f"{p}[{w}]" for p, w, _ in ins_v)}
//   outputs (MSB first): {' '.join(f"{p}[{w}]" for p, w, _ in outs)}
`timescale 1ns/1ps
module replay_{name};
    localparam int NI = {NI};
    localparam int NO = {NO};
    localparam int MAXV = {a.maxv};
    logic [NI-1:0] vin [0:MAXV-1];
    logic [NO-1:0] vout [0:MAXV-1];
    logic {a.clk} = 0;
''' + ''.join(f'    logic {g} = 0;\n' for g in gen_ports) + '\n'.join('    ' + decl(p, w, s) for p, w, s in ins_v + outs) + f'''
`ifdef NETLIST
    // the funcsim netlist flattens struct ports into one port per leaf field
    {name} dut ({netlist_ports});
`else
    {name} dut (.*);
`endif
    int n, errs, cmp, xmask, preroll, maxerr;
    string vecfile;
    initial begin
        if (!$value$plusargs("vec=%s", vecfile)) vecfile = "vectors.hex";
        if (!$value$plusargs("xmask=%d", xmask)) xmask = 0;
        if (!$value$plusargs("maxerr=%d", maxerr)) maxerr = 100000;   // how many MISMATCH lines to print    // 1: X bits of the DUT are don't-care (RTL control)
        if (!$value$plusargs("preroll=%d", preroll)) preroll = 15;   // cycles of vector 0 before the replay: the
                                                                     // funcsim netlist holds GSR for the first 100 ns
        for (int i = 0; i < MAXV; i++) vin[i] = 'x;
        $readmemh(vecfile, vin, 0, MAXV-1);
        $readmemh({{vecfile, ".out"}}, vout, 0, MAXV-1);
    end
    function automatic logic [NO-1:0] xbits(input logic [NO-1:0] v);   // 1 where v is X or Z
        for (int b = 0; b < NO; b++) xbits[b] = (v[b] === 1'bx || v[b] === 1'bz);
    endfunction
{gmask_fn}    initial begin
        errs = 0; cmp = 0; n = 0;
        for (int i = 0; i < preroll; i++) begin
            {{{', '.join(p for p, _, _ in ins_v)}}} = vin[0];
            {edge_seq}
        end
        while (n < MAXV && vin[n] !== 'x) begin
            {{{', '.join(p for p, _, _ in ins_v)}}} = vin[n];
            #4;
            if (n > 2) begin
                cmp++;
                if (xmask ? ((({{{', '.join(p for p, _, _ in outs)}}} ^ vout[n]) & ~xbits({{{', '.join(p for p, _, _ in outs)}}}) & gmask(vout[n])) !== '0)
                          : ({cmp_always}{gate_expr})) begin
                    errs++;
                    if (errs <= maxerr) $display("MISMATCH cycle %0d: got %h exp %h", n, {{{', '.join(p for p, _, _ in outs)}}}, vout[n]);
                end
            end
            #1 {edge_seq_main}
            n++;
        end
        $display("REPLAY %s: %0d cycles, %0d compared, %0d mismatches -> %s", vecfile, n, cmp, errs, errs == 0 ? "PASS" : "FAIL");
        $finish;
    end
endmodule
''')
